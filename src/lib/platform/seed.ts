function seededRun(
  id: string,
  datasetId: string,
  createdAt: string
): EvaluationRun {
  const dataset = datasets.find((item) => item.id === datasetId);
  if (!dataset) throw new Error(datasetId);
  const cases = casesForDataset(dataset);
  const failed = cases.some((item) => item.status === "regressed");
  return {
    id,
    targetType: "rule",
    targetId: "rule_struct",
    targetVersionId: "rv_struct_1",
    datasetId,
    kind: dataset.kind,
    executionPlanId: seedPlans.id,
    status: failed ? "failed" : "passed",
    total: cases.length,
    decisionCounts: summarizeCases(cases),
    changedCount: cases.filter((item) => item.changed).length,
    cases,
    createdAt,
  };
}

