function makeVersion(
  partial: Omit<RuleVersion, "fingerprint" | "labelBindings"> & {
    fingerprint?: string;
    labelBindings?: RuleVersion["labelBindings"];
  }
): RuleVersion {
  const labelBindings = partial.labelBindings ?? [];
  const fingerprint = ruleFingerprint({
    type: partial.type,
    action: partial.action,
    priority: partial.priority,
    config: partial.config,
    sceneId: partial.sceneId,
    applicationId: partial.applicationId,
    labelBindings,
  });
  return { ...partial, labelBindings, fingerprint };
}

